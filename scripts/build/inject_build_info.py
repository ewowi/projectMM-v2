"""inject_build_info.py — PlatformIO pre-script.

Writes a `BuildInfo.h` header into the per-env build directory with the
current BUILD_DATE / BUILD_TIME values, and adds that directory to
CPPPATH. `SystemStatusModule.h` includes the header; only `main.cpp` (the
sole consumer of SystemStatusModule.h) gets recompiled on each build,
which is why we use a header file instead of `env.Append(CPPDEFINES=…)` —
the latter would invalidate every .o file in the build whenever the time
ticks, costing 30 s+ on ESP32 incremental rebuilds.

Ported and minimized from v1's inject_build_info.py: drops the
APP_VERSION read from library.json (no library.json in v2 yet — lands
with OTA in Release 2's Sprint 9).
"""
import os
from datetime import datetime

Import("env")  # noqa: F821 — provided by PlatformIO's SConstruct environment

now = datetime.now()
content = (
    "#pragma once\n"
    "// Generated by scripts/inject_build_info.py — do not edit by hand.\n"
    f'#define BUILD_DATE "{now.strftime("%Y-%m-%d")}"\n'
    f'#define BUILD_TIME "{now.strftime("%H:%M:%S")}"\n'
)

build_dir = env.subst("$BUILD_DIR")                              # noqa: F821
os.makedirs(build_dir, exist_ok=True)
header_path = os.path.join(build_dir, "BuildInfo.h")
# Only write when content actually changed so PIO's mtime-driven dep
# tracking doesn't bust the cache on second-by-second rebuilds inside the
# same wall-clock second.
existing = ""
try:
    with open(header_path) as f:
        existing = f.read()
except FileNotFoundError:
    pass
if existing != content:
    with open(header_path, "w") as f:
        f.write(content)

env.Append(CPPPATH=[build_dir])                                  # noqa: F821
